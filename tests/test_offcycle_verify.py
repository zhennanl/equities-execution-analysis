"""c-113 pins: off-cycle-exit verification chain.

The lesson chain this locks in:
  - Yahoo-searched China tickers must sit on the class-implied
    venue (A -> onshore equity ranges; 'AIR CHINA A' -> 0753.HK
    was the H line — 70 wrong venues found and nulled)
  - onshore codes must be EQUITY ranges (510590.SS is an ETF —
    Yahoo returned it for 'PING AN INS A')
  - member names truncate at ~30 chars and can DROP the class
    letter; prefix_match retries without it and the VENUE
    validator disambiguates the A/H twin lines
  - the audit is regenerated by `offcycle_verify.py audit`
    (was ad-hoc in c-111) and must contain no current members
"""
import json
